<h3>2. Ignorar cupom e comissão</h3>
<p>R$ 15 de desconto na primeira compra em 260 novos = R$ 3.900 que fazem parte do custo de aquisição se o cupom for exclusivo de novos.</p>

<h3>3. Janela de tempo diferente</h3>
<p>Investimento de maio e vendas atribuídas a cliques de abril geram distorção. Alinhe período de investimento e de conversão (ex.: mês civil + atribuição de 7 dias).</p>

<h3>4. Comparar CAC com faturamento</h3>
<p>CAC de R$ 80 em ticket de R$ 50 é desastroso; em ticket de R$ 600 pode ser excelente. Sempre compare com margem, não com receita bruta.</p>

<h3>5. Cortar canal com CAC maior sem ver qualidade</h3>
<p>Meta pode ter CAC R$ 90 e Google R$ 65, mas Meta traz cliente com taxa de 2ª compra em 90 dias de 28% e Google de 12%. O canal “caro” pode ser o melhor.</p>

