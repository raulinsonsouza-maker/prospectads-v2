<p>Útil para planejamento, perigoso se os três números forem chutes. Ex.: ticket R$ 180, 1,4 pedidos/ano, margem 36% → LTV anual bruto ≈ R$ 90,72 de margem por “cliente médio” — mas clientes novos vs fiéis divergem muito.</p>

<h2>Relação LTV/CAC: o número que decide escala</h2>

<p>CAC diz quanto você paga para trazer o cliente. LTV diz quanto ele devolve. A razão entre os dois orienta investimento:</p>

<ul>
    <li><strong>LTV:CAC &lt; 1:1</strong> em 12 meses — modelo insustentável (perde dinheiro na aquisição sem recuperar).</li>
    <li><strong>1:1 a 2:1</strong> — apertado; só funciona com caixa forte ou custo fixo muito baixo.</li>
    <li><strong>3:1 ou mais</strong> em 12 meses — referência clássica para crescimento com margem de segurança.</li>
</ul>

<p>Monte CAC e LTV na mesma planilha, com a mesma definição de cliente novo e a mesma janela de tempo. ROAS sozinho não substitui essa dupla.</p>

<h2>Recompra: onde o LTV é construído</h2>

<p>Em categorias de consumo recorrente (suplementos, café, pet, cosméticos, moda íntima básica), recompra é o motor do LTV. Em compra única de alto ticket (móveis, eletrônicos), LTV depende mais de indicação e cross-sell pontual.</p>

<p>Métricas para acompanhar:</p>

<ul>
    <li><strong>Taxa de recompra 30/60/90 dias</strong> — % de clientes que voltam a comprar.</li>
    <li><strong>Tempo médio entre compras</strong> — define timing de e-mail e oferta.</li>
    <li><strong>Receita repetida / receita total</strong> — lojas maduras passam de 30% a 50%+.</li>
    <li><strong>Churn implícito</strong> — clientes que não voltam em 2× o ciclo médio de recompra.</li>
</ul>

<p>Exemplo: 1.000 clientes novos/mês, 20% recompram em 90 dias com ticket similar → 200 pedidos extras sem CAC de mídia paga. Se margem média é R$ 60, são R$ 12.000/mês que melhoram o LTV da coorte inteira.</p>

<h2>CRM, e-mail e pós-venda: alavancas de LTV</h2>

<p>LTV não cresce só com anúncio. Cresce com:</p>

<ul>
    <li>fluxo pós-compra (guia de uso, lembrete de reposição);</li>
    <li>segmentação por categoria comprada;</li>
    <li>oferta de assinatura ou kit de recompra;</li>
    <li>programa de fidelidade simples (cashback, frete grátis na 3ª compra);</li>
    <li>atendimento que resolve e gera confiança para a próxima vez.</li>
</ul>

<p>Investir R$ 400/mês em ferramenta de e-mail + 4 horas/semana de operação pode elevar recompra em 2–5 pontos percentuais — impacto direto no LTV e no LTV:CAC.</p>

<h2>Quando ROAS baixo é saudável</h2>

<p>Cenário clássico: campanha com ROAS 2,8x na primeira compra, enquanto outra tem 4,5x. A equipe corta a de 2,8x. Seis meses depois, descobre que os clientes da campaña “pior” recompram 35% em 90 dias e a dos 4,5x recompram 9%.</p>

<p>ROAS baixo pode ser saudável quando:</p>

<ul>
    <li>margem da primeira compra + LTV projetado &gt; CAC + custos fixos rateados;</li>
    <li>o canal traz perfil com maior recompra (assinatura, consumível);</li>
    <li>você está em fase de captura de mercado com caixa e estoque para suportar payback longo;</li>
    <li>o ticket sobe na 2ª compra (upsell natural).</li>
</ul>

<p>O oposto também vale: ROAS 6x com margem de 15% e zero recompra pode ser pirotecnia — faturamento bonito no ads e lucro inexistente no fechamento do mês.</p>

<h2>LTV e decisões de produto e catálogo</h2>

<p>SKUs que atraem só caçadores de desconto podem inflar ROAS e destruir LTV. Produtos âncora com margem baixa na primeira compra e alta na reposição (filtro de água, refil, café em grão) são desenhados para LTV, não para ROAS do dia 1.</p>

<p>Analise LTV por:</p>

<ul>
    <li>categoria do primeiro produto comprado;</li>
    <li>cupom usado na primeira compra;</li>
    <li>canal de aquisição;</li>
    <li>região (frete e prazo afetam recompra).</li>
</ul>

<h2>Erros ao usar LTV</h2>

<ul>
    <li>usar faturamento em vez de margem;</li>
    <li>projetar LTV de 24 meses com só 3 meses de histórico;</li>
    <li>ignorar devolução e chargeback na margem;</li>
    <li>tratar marketplace e loja própria como mesmo LTV sem separar;</li>
    <li>escalar CAC porque “o LTV vai compensar” sem medir recompra real.</li>
</ul>

