<p>Oferecer kit (“Leve 2 e economize 12%”) ou complemento (“Meias compatíveis”) na própria página aumenta ticket médio sem novo CAC. Regras: o upsell precisa fazer sentido imediato; preço do bundle deve ser mais claro que conta mental do cliente; não empurrar três upsells antes do botão principal em mobile. Teste um upsell por vez. Loja de skincare que adicionou “Rotina completa” como kit na página do sérum isolado elevou ticket médio de R$ 89 para R$ 134 em 30% dos pedidos daquele SKU — conversão da página caiu 0,2 p.p., mas receita por sessão subiu.</p>

