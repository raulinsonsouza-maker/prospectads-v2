<h3>Descrição longa ou curta?</h3>
<p>O suficiente para responder dúvidas que gerariam contato no suporte. Estruture em blocos escaneáveis; evite parede de texto sem subtítulos. O cliente no mobile lê em diagonal — bullets e H3 ajudam.</p>

<h3>Preciso de vídeo em todo produto?</h3>
<p>Não em todos, mas nos campeões de tráfego e ticket médio alto o vídeo curto costuma pagar o esforço. Comece pelos 5 SKUs que mais recebem cliques de anúncio.</p>

