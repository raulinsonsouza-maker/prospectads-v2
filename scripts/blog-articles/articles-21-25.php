<h2>Como calcular LTV na prática</h2>

<h3>Método 1: histórico por coorte (o mais confiável)</h3>

<p>Pegue todos os clientes que fizeram a <strong>primeira compra em janeiro</strong>. Some a margem de todos os pedidos deles até dezembro. Divida pelo número de clientes da coorte.</p>

