    <li>Taxa de 2ª compra em 120 dias: 26%</li>
    <li>Margem média 2ª compra: R$ 48</li>
    <li>LTV margem 120d estimado: R$ 59,64 + (0,26 × R$ 48) = R$ 72,12</li>
</ul>

<p>Se a meta é LTV:CAC de 3:1 em 120 dias, CAC máximo ≈ R$ 24. Se o CAC real no Meta está em R$ 38, há três caminhos: melhorar conversão do site (cai CAC), aumentar recompra (sobe LTV), ou aceitar payback mais longo com caixa — não “achar” que R$ 38 está bom porque o ROAS do painel mostra 4x.</p>

<h2>CAC blended vs CAC incremental</h2>

<p><strong>Blended:</strong> todo investimento em aquisição ÷ todos os novos — visão geral da loja.</p>

<p><strong>Incremental:</strong> quanto custa o próximo cliente se você aumentar verba em R$ 5 mil — costuma ser mais caro que a média porque campanhas saturam.</p>

<p>Ao escalar, monitore se CAC sobe mais rápido que volume. Se em 30 dias você dobrou mídia e CAC subiu 60% com apenas 30% mais clientes novos, a escala marginal está cara — hora de otimizar criativo, público ou landing antes de mais verba.</p>

<h2>Organização de dados entre marketing e financeiro</h2>

<p>Marketing costuma ver CPA do ads; financeiro vê margem líquida. Alinhe reunião mensal com planilha única: investimento por canal (ads), novos clientes (ERP), margem por pedido (financeiro ou BI). Sem essa ponte, CAC vira discussão de opinião.</p>

<p>Ferramentas como planilhas Google, Looker Studio ou export CSV do ERP resolvem no início. O importante é mesma definição de “cliente novo” e mesmo período.</p>

<h2>CAC em marketplace vs loja própria</h2>

<p>No marketplace, “aquisição” inclui taxa da plataforma, ads internos (ML Ads, Shopee Ads) e promoções patrocinadas. Calcule CAC separado da loja própria — misturar distorce decisão de onde investir próximo real.</p>

<p>Muitas marcas usam marketplace para volume e loja própria para margem e lista — CAC da loja própria pode ser maior em reais, mas LTV com e-mail e CRM costuma compensar.</p>

<h2>CAC em sazonalidade (Black Friday e datas sazonais)</h2>

<p>Em novembro, CPM sobe e CAC costuma subir 20% a 50%. Compare CAC de outubro vs novembro vs dezembro — não use CAC de pico como regra o ano inteiro. Planeje teto de CAC maior na campanha sazonal só se estoque, equipe e margem promocional suportarem.</p>

<p>Após a data, muitas lojas cortam mídia abruptamente e perdem remarketing quente — melhor reduzir gradualmente e manter fluxo de e-mail para quem comprou na promoção.</p>

<h2>Influenciador e CAC híbrido</h2>

<p>Pagamento fixo + comissão: aloque o fixo como mídia de awareness e a comissão por venda nova no CAC. Cupom exclusivo do influenciador permite rastrear novos no ERP. Se 80% dos pedidos com cupom são de clientes que já compraram, o influenciador está cannibalizando, não adquirindo — ajuste comissão ou público.</p>

<h2>Quando o CAC sobe mas você não deve pausar</h2>

<ul>
    <li>conversão do site caiu por bug ou lentidão (corrigir site primeiro);</li>
    <li>sazonalidade de CPM temporária;</li>
    <li>você mudou atribuição ou passou a contar só novos (CAC “subiu” artificialmente);</li>
    <li>LTV da coorte recente subiu (ex.: novo produto de assinatura).</li>
</ul>

<p>Quando pausar de verdade: CAC acima do teto por 4+ semanas, LTV flat ou caindo, estoque crítico, ou reclamação/NPS despencando — sinal de crescimento ruim.</p>

<h2>Simulação de escala com CAC estável</h2>

<p>Se CAC = R$ 72 e você adiciona R$ 10.000/mês em mídia com eficiência constante, novos clientes extras ≈ 139. Com margem 1ª compra R$ 58, contribuição imediata R$ 8.062 — ainda abaixo do investimento incremental se não houver recompra. Com 25% recompra em 90 dias (margem R$ 45), adiciona ~R$ 1.566 de margem futura na coorte — o payback melhora, mas ainda exige olhar LTV completo. Esse exercício evita “dobrei a verba, dobrei o lucro” automático.</p>

<h2>CAC e criativo: o que o número não diz</h2>

<p>CAC alto pode ser público errado, oferta fraca ou página lenta — não só “anúncio ruim”. Antes de cortar verba, segmente CAC por landing page e por criativo. Criativo com CTR alto e CAC alto muitas vezes atrai curioso; criativo com CTR médio e CAC baixo atrai comprador. Otimize para custo por cliente novo, não para vaidade de CTR.</p>

<h2>Template de relatório mensal de CAC (copiar)</h2>

<p>Seção 1 — Resumo: investimento total, novos clientes, CAC blended, variação vs mês anterior. Seção 2 — Por canal: Meta, Google, afiliados, orgânico assistido. Seção 3 — Qualidade: ticket e margem 1ª compra por canal. Seção 4 — Ações: o que escalar, o que pausar, o que testar na landing. Seção 5 — Hipóteses LTV: recompra preliminar da coorte do mês. Uma página, enviada até dia 5 — evita reunião de duas horas sem número.</p>

<h2>CAC e equipe comercial interna</h2>

<p>Se parte das vendas vem de humano (WhatsApp, telefone) após clique pago, decida se o custo do vendedor entra no CAC ou em custo operacional. Consistência importa mais que a classificação perfeita. Muitas lojas B2B híbridas subestimam CAC porque não rateiam tempo de fechamento — parecem eficientes no ads e caras na folha.</p>

<h2>Glossário rápido (para alinhar o time)</h2>

<ul>
    <li><strong>CAC:</strong> custo para conquistar cliente novo.</li>
    <li><strong>CPA:</strong> custo por pedido no ads (pode incluir recorrentes).</li>
    <li><strong>Margem de contribuição:</strong> o que sobra após custos variáveis do pedido.</li>
    <li><strong>LTV:</strong> margem acumulada do cliente no período.</li>
    <li><strong>Payback:</strong> tempo até margem acumulada = CAC.</li>
    <li><strong>ROAS:</strong> receita atribuída ÷ gasto em mídia (não é lucro).</li>
</ul>

<p>Quando todos usam os mesmos termos, a reunião deixa de ser “achismo de marketing vs financeiro” e vira decisão de investimento.</p>

<h2>Meta de CAC por fase da loja</h2>

<p><strong>Validação (0–3 meses):</strong> priorize aprender, não escala; CAC alto pode ser aceitável se volume de dados ainda é baixo. <strong>Crescimento (6–18 meses):</strong> defina teto por margem e LTV 90d; escale em degraus de 20% de verba. <strong>Maturidade:</strong> otimize LTV e mix de canal; CAC tende a subir se não renovar criativo e público. Documentar em qual fase você está evita comparar sua loja de 4 meses com benchmark de operação de 5 anos.</p>

<h2>Integrar CAC com orçamento de mídia mensal</h2>

<p>Se o teto de CAC é R$ 70 e você quer 200 clientes novos no mês, orçamento de aquisição ≈ R$ 14.000 — antes de agência e cupons. Se o ERP mostra que no mês passado vieram 150 novos com R$ 14.000, CAC real foi R$ 93: ou o teto estava errado ou a eficiência caiu. Ajuste verba ou corrija funil; não aumente orçamento sem recalcular CAC alvo.</p>

<h2>Do CAC à decisão de escala em uma frase</h2>

<p>Calcule CAC por canal com clientes novos reais, compare com margem da primeira compra e com LTV em 90–365 dias, defina teto e só escale quando a conta fechar com folga para imprevistos de estoque, devolução e sazonalidade. CAC saudável não é o menor possível — é o que compra clientes que o negócio consegue lucrar e reter.</p>

<h2>Perguntas frequentes</h2>

<h3>CAC e CPA são a mesma coisa?</h3>
<p>CPA (custo por aquisição/pedido) costuma ser por compra no painel de anúncios. CAC no varejo deve focar em <strong>cliente novo</strong>. Se cada cliente compra uma vez, CPA ≈ CAC; com recompra, divergem.</p>

<h3>Quanto tempo para o CAC estabilizar após lançar loja?</h3>
<p>Em geral 60–90 dias de volume mínimo (centenas de cliques e dezenas de vendas novas por canal). Antes disso, o número oscila demais para escalar agressivamente.</p>

<h3>Incluo salário do gestor de tráfego interno?</h3>
<p>Se a função existe só para aquisição, pode ratear. Se a pessoa também cuida de site, e-mail e marketplace, aloque percentual realista — senão o CAC fica artificialmente alto.</p>

<h3>CAC bom para moda é o mesmo para suplementos?</h3>
<p>Não. Moda costuma ter devolução maior e margem apertada; suplementos podem ter recompra previsível. Defina teto de CAC por margem do seu SKU médio, não por benchmark genérico de mercado.</p>
