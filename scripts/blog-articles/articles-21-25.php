<p>Repita para cada mês de aquisição. Você verá se clientes adquiridos no Meta em março valem mais que os do Google em abril.</p>

<h3>Método 2: estimativa por taxa de recompra</h3>

<p>Quando ainda há pouco histórico:</p>

<ol>
    <li>Calcule ticket médio e margem % da 1ª compra.</li>
    <li>Meça % de clientes que recompram em 90 dias (ex.: 22%).</li>
    <li>Meça ticket e margem médios da 2ª compra.</li>
    <li>Projete: LTV 90d ≈ margem 1ª + (22% × margem média 2ª compra).</li>
</ol>

<p>Exemplo: margem 1ª = R$ 70; 22% recompram com margem média R$ 55 na 2ª → LTV 90d estimado = R$ 70 + (0,22 × R$ 55) = R$ 82,10.</p>

