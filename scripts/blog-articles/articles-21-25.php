<h2>Quando subir ou baixar investimento com base no CAC</h2>

<p><strong>Subir verba</strong> quando: CAC estável ou caindo, margem da 1ª compra + recompra projetada pagam o modelo, estoque e atendimento aguentam volume.</p>

<p><strong>Manter</strong> quando: CAC subiu mas conversão do site caiu — corrigir funil antes de culpar só a mídia.</p>

<p><strong>Cortar ou pausar</strong> quando: CAC acima do teto definido por 3+ semanas sem sinal de LTV, ou operação não entrega prazo e gera reembolso que come margem.</p>

