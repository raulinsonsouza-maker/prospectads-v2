    <li>Taxa de recompra 90d da última coorte grande.</li>
    <li>LTV margem 90d ou 12m da coorte (quando houver dados).</li>
    <li>LTV:CAC — decisão de escala baseada aqui, não só no ROAS.</li>
</ol>

<h2>Payback: em quantos meses o cliente se paga</h2>

<p>Payback é o tempo até a margem acumulada do cliente igualar o CAC. Exemplo: CAC R$ 85, margem na 1ª compra R$ 52 — falta R$ 33. Se a 2ª compra em 60 dias traz margem R$ 45, payback ocorre na segunda compra. Se não houver 2ª compra, o cliente nunca pagou a aquisição.</p>

<p>Calcule payback por canal de aquisição. Meta pode ter payback 90 dias; Google 45 dias — mesmo com ROAS similar na primeira compra.</p>

<h2>Assinatura e LTV previsível</h2>

<p>Modelos de assinatura (café, ração, fraldas, suplementos) elevam LTV porque reduzem atrito da recompra. O LTV passa a incluir churn mensal: se 8% cancelam por mês, a vida média da assinatura é ~12,5 meses — use isso na projeção, não “todo mundo fica para sempre”.</p>

<p>MRR (receita recorrente mensal) × margem × vida média = componente recorrente do LTV. Some compras avulsas fora da assinatura para visão completa.</p>

<h2>Como CRM alimenta LTV (fluxos mínimos)</h2>

<p>Sem CRM sofisticado, quatro gatilhos já movem LTV:</p>

<ul>
    <li>D+3 pós-entrega: conteúdo de uso + pedido de review;</li>
    <li>D+30 sem recompra: e-mail com best-seller da categoria que comprou;</li>
    <li>D+60: win-back com benefício testado;</li>
    <li>aniversário de primeira compra: oferta exclusiva lista VIP.</li>
</ul>

<p>Meça lift: compare coorte que recebe fluxos vs coorte histórica antes dos fluxos (ou teste A/B por segmento).</p>

<h2>Investir em aquisição quando LTV ainda é incerto</h2>

<p>Loja com menos de 6 meses não tem LTV de 12 meses medido — use LTV 90 dias e seja conservador no CAC. Prefira crescer mais devagar com CAC abaixo da margem da 1ª compra do que escalar no escuro esperando recompra que não foi validada.</p>

<p>Quando a recompra em 90 dias passa de 15%–20% em consumível, você ganha permissão para subir CAC alvo — o negócio deixou de ser “uma venda só”.</p>

<h2>Segmentação de LTV: clientes VIP</h2>

<p>Identifique o top 10% por margem acumulada em 12 meses. Esse grupo pode ter LTV 5× a média. Trate com frete prioritário, acesso antecipado e atendimento dedicado — custo baixo, impacto alto na retenção. Não gastar mídia paga para re-adquirir quem já é VIP; use e-mail e WhatsApp 1:1.</p>

<h2>Devolução e LTV real</h2>

<p>LTV de faturamento que ignora devolução infla o número. Desconte pedidos devolvidos e chargeback da margem da coorte. Moda com 25% de devolução tem LTV líquido muito menor que o bruto — decisões de CAC baseadas em LTV bruto levam a escala perigosa.</p>

<h2>Produto e margem: o alavanca antes do anúncio</h2>

<p>Às vezes o ROAS cai porque o mix mudou para SKU de margem baixa, não porque o tráfego piorou. Cruze LTV por SKU de entrada. Se afiliados e campanhas empurram sempre o produto promocional de margem 12%, o LTV da coorte desaba — corrija catálogo e criativo antes de culpar o canal.</p>

<h2>Dashboard semanal LTV + CAC (modelo)</h2>

<p>Toda segunda, 30 minutos:</p>

<ol>
    <li>Novos clientes última semana e CAC semanal.</li>
    <li>Receita repetida / total da semana.</li>
    <li>Coorte do mês: % com 2ª compra até hoje.</li>
    <li>ROAS 7d por campanha (alerta, não decisão única).</li>
    <li>Uma ação: qual fluxo de CRM testar esta semana.</li>
</ol>

<h2>Comparar coortes de aquisição mês a mês</h2>

<p>Clientes adquiridos em janeiro com frete grátis podem ter LTV diferente dos de março com full price. Não misture coortes na mesma média. Marketing deve saber qual promoção de aquisição treina cliente que volta vs cliente que só compra com desconto.</p>

<h2>LTV e precificação</h2>

<p>Se o LTV sobe quando você introduz kit com margem maior na 2ª compra, o problema não era tráfego — era arquitetura de oferta. Teste bundles, assinatura e programa de pontos antes de concluir que “não dá para escalar”. ROAS da primeira compra é capítulo um; LTV é o livro inteiro.</p>

<h2>Cenários numéricos: ROAS 3x vs 5x</h2>

<p><strong>Cenário A:</strong> ROAS 5x, ticket R$ 100, margem 30%, sem recompra → margem R$ 30, se CAC = R$ 25, sobra R$ 5 por cliente — frágil.<br>
<strong>Cenário B:</strong> ROAS 3x, ticket R$ 100, margem 30%, CAC R$ 40, margem 1ª = R$ 30 (prejuízo R$ 10), mas 30% recompram em 60d com margem R$ 35 → LTV 60d = R$ 30 + R$ 10,5 = R$ 40,5, ainda abaixo do CAC — precisa 2ª compra maior ou 3ª.<br>
<strong>Cenário C:</strong> ROAS 3,5x, CAC R$ 35, 35% recompra, margem 2ª R$ 45 → LTV 90d ≈ R$ 46, payback ok.</p>

<p>Os números são ilustrativos; o exercício mostra por que gestores experientes pedem planilha de margem + recompra antes de celebrar ROAS.</p>

<h2>Comunicar LTV para o time</h2>

<p>Designer, atendimento e mídia devem entender que segunda compra importa. Metas só de “vendas novas” incentivam desconto agressivo que destrói margem e não cria hábito. Inclua % de recompra ou receita repetida no dashboard visível da equipe — alinha todos com LTV, não só com campanha da semana.</p>

<h2>Ferramentas para medir LTV sem BI caro</h2>

<p>Export mensal de clientes do ERP: ID, data 1ª compra, receita e margem por pedido. Planilha com SOMASES por cliente e coorte. Shopify e Nuvemshop têm relatórios de clientes recorrentes — use como ponto de partida. Quando passar de ~500 pedidos/mês, BI (Looker, Metabase) automatiza; antes disso, planilha disciplinada resolve.</p>

<h2>Quando focar em ROAS mesmo assim</h2>

<p>ROAS ainda serve para otimizar criativo e público no curto prazo, pausar campanha com prejuízo imediato óbvio e comparar anúncios entre si. Só não confunda otimização de campanha com saúde do negócio. Fechamento mensal sempre volta a margem, CAC e LTV.</p>

<h2>LTV negativo e clientes que só compram em promoção</h2>

<p>Se 40% dos “recorrentes” só voltam com cupom de 30%, o LTV real é menor que a planilha mostra — desconte o desconto da margem. Estratégia: segmentar compradores promocionais e testar recompra com valor agregado (conteúdo, acesso antecipado, frete) antes de novo cupom. Cliente treinado a esperar desconto destrói LTV e sobe CAC efetivo no longo prazo.</p>

<h2>Síntese: por que LTV vence o ROAS no dia a dia</h2>

<p>ROAS responde “a campanha devolveu receita este mês?”. LTV responde “esse cliente vale a pena para o negócio?”. E-commerce sustentável precisa das duas respostas, mas a estratégia de crescimento — quanto pagar por novo, quanto investir em CRM, se o produto precisa de assinatura — nasce do LTV e da margem, não do múltiplo verde no Gerenciador de Anúncios.</p>

<p>Próximo passo prático: exporte a coorte dos últimos 90 dias, calcule margem acumulada por cliente, cruze com canal de aquisição e com produto da primeira compra. Uma planilha honesta nesse formato costuma revelar mais que dezenas de horas debatendo ROAS no painel.</p>

<h2>Perguntas frequentes</h2>

<h3>LTV é o mesmo que ticket médio?</h3>
<p>Não. Ticket médio é valor por pedido. LTV é a soma (em margem) de vários pedidos do mesmo cliente ao longo do tempo.</p>

<h3>Preciso de 12 meses de loja para calcular LTV?</h3>
<p>Para LTV de 12 meses, sim, idealmente. Para decisões operacionais, LTV de 90 dias por coorte já orienta muito — desde que você não projete 24 meses com dados de um trimestre.</p>

<h3>Marketplace entra no LTV?</h3>
<p>Calcule separado. Taxa de marketplace, controle do relacionamento e recompra na plataforma mudam o jogo. LTV da loja própria costuma ser mais alto quando CRM e e-mail funcionam.</p>

<h3>ROAS deixou de importar?</h3>
<p>Importa como termômetro de eficiência da mídia no curto prazo. Mas decisão de escala sustentável deve passar por margem, CAC e LTV — não pelo múltiplo do painel sozinho.</p>
